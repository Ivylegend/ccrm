const assert = require('node:assert/strict');
const { handleWebsiteMail } = require(process.argv[2]);
const env = { RESEND_API_KEY: 'test-key', RESEND_FROM_EMAIL: 'CCRM <website@contact.ccrm.com.ng>' };
const contact = { name: 'Test Sender', email: 'sender@example.com', subject: 'Resources', message: 'Please send information.' };
let calls = [];
global.fetch = async (url, init) => { calls.push({ url, ...init, body: JSON.parse(init.body) }); return new Response('{}', { status: 200 }); };
const request = (body, headers = {}) => new Request('https://ccrm.com.ng/api/contact', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://ccrm.com.ng', ...headers }, body: typeof body === 'string' ? body : JSON.stringify(body) });
(async () => {
  assert.equal((await handleWebsiteMail(request({}), env, 'contact')).status, 400);
  assert.equal((await handleWebsiteMail(request({ ...contact, email: 'invalid' }), env, 'contact')).status, 400);
  assert.equal((await handleWebsiteMail(request({ ...contact, message: 'x'.repeat(5001) }), env, 'contact')).status, 400);
  assert.equal((await handleWebsiteMail(request('x'.repeat(12001)), env, 'contact')).status, 413);
  assert.equal((await handleWebsiteMail(request('{'), env, 'contact')).status, 400);
  assert.equal((await handleWebsiteMail(request([]), env, 'contact')).status, 400);
  assert.equal((await handleWebsiteMail(request(contact, { Origin: 'https://example.com' }), env, 'contact')).status, 403);
  assert.equal((await handleWebsiteMail(request(contact, { 'Content-Type': 'text/plain' }), env, 'contact')).status, 415);
  assert.equal((await handleWebsiteMail(request(contact), {}, 'contact')).status, 503);
  assert.equal((await handleWebsiteMail(request({ website: 'spam' }), env, 'contact')).status, 200);
  assert.equal(calls.length, 0);
  assert.equal((await handleWebsiteMail(request(contact), env, 'contact')).status, 200);
  assert.equal(calls.length, 1);
  assert.equal(calls[0].url, 'https://api.resend.com/emails');
  assert.deepEqual(calls[0].body.to, ['ccrmjuly2022@gmail.com']);
  assert.equal(calls[0].body.reply_to, contact.email);
  assert.equal(calls[0].body.from, env.RESEND_FROM_EMAIL);
  assert.match(calls[0].body.text, /Please send information/);
  assert.equal((await handleWebsiteMail(request({ email: 'subscriber@example.com' }), env, 'newsletter')).status, 200);
  assert.equal(calls.length, 2);
  assert.match(calls[1].body.subject, /subscription request/);
  assert.match(calls[1].body.text, /subscriber@example.com/);
  global.fetch = async () => new Response('{}', { status: 429 });
  assert.equal((await handleWebsiteMail(request(contact), env, 'contact')).status, 502);
  global.fetch = async () => { throw new Error('network error'); };
  assert.equal((await handleWebsiteMail(request(contact), env, 'contact')).status, 502);
  console.log('PASS: validation, origin checks, honeypot, configuration failure, contact/newsletter delivery payloads, provider rejection and network failure; no real emails sent.');
})().catch(error => { console.error(error); process.exitCode = 1; });
